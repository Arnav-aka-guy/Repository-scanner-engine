import type { SystemDesignDiagram } from '../../services/systemDesign';
import type { Point, SystemDesignLayout } from './systemDesignLayout';
import {
  CANVAS_BG,
  EDGE_COLOR,
  GROUP_THEME,
  KIND_ACCENT,
  KIND_LABEL,
  NODE_BG,
  NODE_BORDER,
  TEXT_PRIMARY,
  TEXT_SECONDARY,
} from './diagramTheme';

const PAD = 40;
const TITLE_H = 64;
const FONT = "Inter, 'Segoe UI', Arial, sans-serif";

function esc(text: string): string {
  return text
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

function truncate(text: string, max: number): string {
  return text.length > max ? `${text.slice(0, max - 1)}…` : text;
}

function pathFromPoints(points: Point[]): string {
  if (points.length === 0) return '';
  return points.map((p, i) => `${i === 0 ? 'M' : 'L'}${p.x.toFixed(1)},${p.y.toFixed(1)}`).join(' ');
}

/** Build a standalone SVG (no external fonts or images) of the laid-out diagram. */
export function buildDiagramSvg(diagram: SystemDesignDiagram, layout: SystemDesignLayout): string {
  const width = Math.ceil(layout.width + PAD * 2);
  const height = Math.ceil(layout.height + PAD * 2 + TITLE_H);
  const ox = PAD;
  const oy = PAD + TITLE_H;
  const parts: string[] = [];

  parts.push(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}" font-family="${FONT}">`
  );
  parts.push('<defs>');
  Object.entries(EDGE_COLOR).forEach(([kind, color]) => {
    parts.push(
      `<marker id="arrow-${kind}" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0,0 L10,5 L0,10 z" fill="${color}"/></marker>`
    );
  });
  parts.push('</defs>');
  parts.push(`<rect width="100%" height="100%" fill="${CANVAS_BG}"/>`);
  parts.push(
    `<text x="${PAD}" y="${PAD + 22}" fill="${TEXT_PRIMARY}" font-size="22" font-weight="700">${esc(diagram.title)}</text>`
  );
  parts.push(
    `<text x="${PAD}" y="${PAD + 46}" fill="${TEXT_SECONDARY}" font-size="12">${esc(
      truncate(`Generated by ${diagram.generated_by} · ${diagram.detail} view`, 120)
    )}</text>`
  );

  layout.groups.forEach((g) => {
    const t = GROUP_THEME[g.id];
    parts.push(
      `<rect x="${ox + g.x}" y="${oy + g.y}" width="${g.width}" height="${g.height}" rx="14" fill="${t.fill}" stroke="${t.stroke}" stroke-width="1.5" stroke-dasharray="6 4"/>`
    );
    parts.push(
      `<text x="${ox + g.x + g.width / 2}" y="${oy + g.y + 28}" text-anchor="middle" fill="${t.title}" font-size="14" font-weight="700" letter-spacing="0.5">${esc(g.label)}</text>`
    );
  });

  layout.edges.forEach((e) => {
    const color = EDGE_COLOR[e.kind] ?? EDGE_COLOR.dependency;
    const pts = e.points.map((p) => ({ x: p.x + ox, y: p.y + oy }));
    parts.push(
      `<path d="${pathFromPoints(pts)}" fill="none" stroke="${color}" stroke-opacity="0.75" stroke-width="1.6" marker-end="url(#arrow-${
        EDGE_COLOR[e.kind] ? e.kind : 'dependency'
      })"/>`
    );
    if (e.label && pts.length >= 2) {
      const mid = pts[Math.floor((pts.length - 1) / 2)];
      const next = pts[Math.floor((pts.length - 1) / 2) + 1] ?? mid;
      const lx = (mid.x + next.x) / 2;
      const ly = (mid.y + next.y) / 2;
      const w = e.label.length * 6.4 + 12;
      parts.push(
        `<rect x="${lx - w / 2}" y="${ly - 9}" width="${w}" height="18" rx="4" fill="${CANVAS_BG}" stroke="${color}" stroke-opacity="0.4"/>`
      );
      parts.push(
        `<text x="${lx}" y="${ly + 4}" text-anchor="middle" fill="${TEXT_PRIMARY}" font-size="10.5">${esc(e.label)}</text>`
      );
    }
  });

  layout.nodes.forEach((n) => {
    const accent = KIND_ACCENT[n.kind] ?? KIND_ACCENT.module;
    const x = ox + n.x;
    const y = oy + n.y;
    parts.push(
      `<rect x="${x}" y="${y}" width="${n.width}" height="${n.height}" rx="8" fill="${NODE_BG}" stroke="${NODE_BORDER}" stroke-width="1.2"/>`
    );
    parts.push(`<rect x="${x}" y="${y}" width="4" height="${n.height}" rx="2" fill="${accent}"/>`);
    parts.push(
      `<text x="${x + 14}" y="${y + 17}" fill="${accent}" font-size="9" font-weight="700" letter-spacing="0.6">${esc(
        (KIND_LABEL[n.kind] ?? n.kind).toUpperCase()
      )}</text>`
    );
    parts.push(
      `<text x="${x + 14}" y="${y + 36}" fill="${TEXT_PRIMARY}" font-size="13.5" font-weight="600">${esc(
        truncate(n.label, 26)
      )}</text>`
    );
    if (n.tech?.length) {
      parts.push(
        `<text x="${x + 14}" y="${y + 55}" fill="${TEXT_SECONDARY}" font-size="10.5">${esc(
          truncate(n.tech.slice(0, 3).join(' · '), 34)
        )}</text>`
      );
    }
  });

  parts.push('</svg>');
  return parts.join('');
}

export function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

export function downloadText(text: string, filename: string, mime = 'text/plain'): void {
  downloadBlob(new Blob([text], { type: `${mime};charset=utf-8` }), filename);
}

/** Render the SVG to a PNG (2x scale for sharp prints) and download it. */
export async function downloadPng(svg: string, filename: string, scale = 2): Promise<void> {
  const svgBlob = new Blob([svg], { type: 'image/svg+xml;charset=utf-8' });
  const url = URL.createObjectURL(svgBlob);
  try {
    const img = new Image();
    await new Promise<void>((resolve, reject) => {
      img.onload = () => resolve();
      img.onerror = () => reject(new Error('Could not render the diagram image.'));
      img.src = url;
    });
    const canvas = document.createElement('canvas');
    canvas.width = Math.ceil(img.width * scale);
    canvas.height = Math.ceil(img.height * scale);
    const ctx = canvas.getContext('2d');
    if (!ctx) throw new Error('Canvas is not available in this browser.');
    ctx.scale(scale, scale);
    ctx.drawImage(img, 0, 0);
    const blob = await new Promise<Blob | null>((resolve) => canvas.toBlob(resolve, 'image/png'));
    if (!blob) throw new Error('Could not create the PNG file.');
    downloadBlob(blob, filename);
  } finally {
    URL.revokeObjectURL(url);
  }
}

export function safeFileName(text: string): string {
  return (
    text
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/^-+|-+$/g, '')
      .slice(0, 60) || 'system-design'
  );
}
